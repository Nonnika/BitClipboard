import AppKit
import UniformTypeIdentifiers

public enum PasteboardReader {
    public static let ignoredTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    ]

    public static func read(_ pasteboard: NSPasteboard) -> ClipboardContent? {
        guard !ignoredTypes.contains(where: { pasteboard.types?.contains($0) == true }) else { return nil }
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            guard urls.count == 1 else { return nil }
            return imageFileContent(at: urls[0])
        }
        // Don't capture a file's name or generic icon as clipboard content.
        if pasteboard.types?.contains(.fileURL) == true { return nil }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type) {
                // Keep polling bounded for very large clipboard images.
                return imageContent(from: data)
            }
        }
        guard let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= 2 * 1024 * 1024 else { return nil }
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        let isLink = TextExtraction.isStandaloneLink(trimmed)
        return ClipboardContent(kind: isLink ? .link : .text, text: text)
    }

    public static func imageFileContent(at url: URL) -> ClipboardContent? {
        guard url.isFileURL,
              let attributes = try? url.resourceValues(forKeys: [.contentTypeKey, .fileSizeKey, .isRegularFileKey]),
              attributes.isRegularFile == true,
              attributes.contentType?.conforms(to: .image) == true,
              let size = attributes.fileSize, size <= 25 * 1024 * 1024,
              let data = try? Data(contentsOf: url, options: .mappedIfSafe) else { return nil }
        return imageContent(from: data)
    }

    private static func imageContent(from data: Data) -> ClipboardContent? {
        guard data.count <= 25 * 1024 * 1024,
              let bitmap = NSBitmapImageRep(data: data),
              let png = bitmap.representation(using: .png, properties: [:]) else { return nil }
        return ClipboardContent(kind: .image, text: "\(bitmap.pixelsWide) × \(bitmap.pixelsHigh)", imageData: png)
    }
}
